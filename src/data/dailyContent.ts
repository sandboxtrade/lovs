function hashDayKey(dayKey: string, salt: number) {
  let hash = 2166136261 ^ salt
  for (let index = 0; index < dayKey.length; index += 1) {
    hash ^= dayKey.charCodeAt(index)
    hash = Math.imul(hash, 16777619)
  }
  return Math.abs(hash >>> 0)
}

export function getDailyContent(dayKey: string) {
  return {
    question: questions[hashDayKey(dayKey, 11) % questions.length],
    choice: choices[hashDayKey(dayKey, 29) % choices.length],
    quest: quests[hashDayKey(dayKey, 47) % quests.length],
  }
}
